export class Sha256 {
  private readonly h = Uint32Array.of(
    0x6a09e667,
    0xbb67ae85,
    0x3c6ef372,
    0xa54ff53a,
    0x510e527f,
    0x9b05688c,
    0x1f83d9ab,
    0x5be0cd19,
  );
  private readonly w = new Uint32Array(64);
  /** A partial block. */
  private readonly buf = new Uint8Array(64);
  private bufLen = 0;
  private length = 0;

  update(bytes: Uint8Array): void {
    this.length += bytes.length;
    let at = 0;
    if (this.bufLen > 0) {
      const n = Math.min(64 - this.bufLen, bytes.length);
      this.buf.set(bytes.subarray(0, n), this.bufLen);
      this.bufLen += n;
      at = n;
      if (this.bufLen < 64) return;
      this.block(this.buf, 0);
      this.bufLen = 0;
    }
    for (; at + 64 <= bytes.length; at += 64) this.block(bytes, at);
    if (at < bytes.length) {
      this.buf.set(bytes.subarray(at));
      this.bufLen = bytes.length - at;
    }
  }

  /** The digest as lowercase hex. The hash takes no more input after this. */
  digest(): string {
    const bits = this.length * 8;
    const tail = new Uint8Array(this.bufLen < 56 ? 64 - this.bufLen : 128 - this.bufLen);
    tail[0] = 0x80;
    const view = new DataView(tail.buffer);
    view.setUint32(tail.length - 8, Math.floor(bits / 0x100000000));
    view.setUint32(tail.length - 4, bits >>> 0);
    this.update(tail);
    let out = '';
    for (const v of this.h) out += v.toString(16).padStart(8, '0');
    return out;
  }

  private block(b: Uint8Array, at: number): void {
    const w = this.w;
    for (let i = 0; i < 16; i++) {
      const j = at + i * 4;
      w[i] =
        ((b[j] as number) << 24) |
        ((b[j + 1] as number) << 16) |
        ((b[j + 2] as number) << 8) |
        (b[j + 3] as number);
    }
    for (let i = 16; i < 64; i++) {
      const x = w[i - 15] as number;
      const y = w[i - 2] as number;
      const s0 = ((x >>> 7) | (x << 25)) ^ ((x >>> 18) | (x << 14)) ^ (x >>> 3);
      const s1 = ((y >>> 17) | (y << 15)) ^ ((y >>> 19) | (y << 13)) ^ (y >>> 10);
      w[i] = ((w[i - 16] as number) + s0 + (w[i - 7] as number) + s1) | 0;
    }
    const h = this.h;
    let a = h[0] as number;
    let b2 = h[1] as number;
    let c = h[2] as number;
    let d = h[3] as number;
    let e = h[4] as number;
    let f = h[5] as number;
    let g = h[6] as number;
    let hh = h[7] as number;
    for (let i = 0; i < 64; i++) {
      const S1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + (K[i] as number) + (w[i] as number)) | 0;
      const S0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
      const maj = (a & b2) ^ (a & c) ^ (b2 & c);
      const t2 = (S0 + maj) | 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b2;
      b2 = a;
      a = (t1 + t2) | 0;
    }
    h[0] = (h[0] as number) + a;
    h[1] = (h[1] as number) + b2;
    h[2] = (h[2] as number) + c;
    h[3] = (h[3] as number) + d;
    h[4] = (h[4] as number) + e;
    h[5] = (h[5] as number) + f;
    h[6] = (h[6] as number) + g;
    h[7] = (h[7] as number) + hh;
  }
}
